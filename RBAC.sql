-- =====================================================================
-- RBAC - NÚCLEO DE SEGURANÇA (RBAC + USERS + LOGS + SESSIONS)
-- =====================================================================

DROP DATABASE IF EXISTS RBAC;
CREATE DATABASE IF NOT EXISTS RBAC
    DEFAULT CHARACTER SET utf8mb4
    DEFAULT COLLATE utf8mb4_unicode_ci;

USE RBAC;

SET FOREIGN_KEY_CHECKS = 0;
SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

-- =====================================================================
-- 1. PERFIS
-- =====================================================================
CREATE TABLE IF NOT EXISTS PROFILES (
    PROFILE_ID          INT AUTO_INCREMENT PRIMARY KEY,
    PROFILE_CODE        VARCHAR(10)  NOT NULL UNIQUE,
    PROFILE_NAME        VARCHAR(50)  NOT NULL UNIQUE,
    PROFILE_DESCRIPTION TEXT         NULL,
    PROFILE_STATUS      ENUM('ACTIVE','INACTIVE') DEFAULT 'INACTIVE',
    PROFILE_CREATEBY    INT NULL,
    PROFILE_UPDATEBY    INT NULL,
    PROFILE_CREATEAT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PROFILE_UPDATEAT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 2. AÇÕES (verbos do RBAC)
-- =====================================================================
CREATE TABLE IF NOT EXISTS ACTIONS (
    ACTION_ID          INT AUTO_INCREMENT PRIMARY KEY,
    ACTION_CODE        VARCHAR(10)  NOT NULL UNIQUE,
    ACTION_NAME        VARCHAR(50)  NOT NULL UNIQUE,
    ACTION_DESCRIPTION TEXT         NULL,
    ACTION_STATUS      ENUM('ACTIVE','INACTIVE') DEFAULT 'ACTIVE',
    ACTION_CREATEBY    INT NULL,
    ACTION_UPDATEBY    INT NULL,
    ACTION_CREATEAT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ACTION_UPDATEAT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 3. MÓDULOS (recursos do RBAC)
-- =====================================================================
CREATE TABLE IF NOT EXISTS MODULES (
    MODULE_ID          INT AUTO_INCREMENT PRIMARY KEY,
    MODULE_CODE        VARCHAR(10)  NOT NULL UNIQUE,
    MODULE_NAME        VARCHAR(50)  NOT NULL UNIQUE,
    MODULE_DESCRIPTION TEXT         NULL,
    MODULE_STATUS      ENUM('ACTIVE','INACTIVE') DEFAULT 'INACTIVE',
    MODULE_CREATEBY    INT NULL,
    MODULE_UPDATEBY    INT NULL,
    MODULE_CREATEAT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    MODULE_UPDATEAT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 4. PERMISSÕES (perfil × ação × módulo)
-- =====================================================================
CREATE TABLE IF NOT EXISTS PERMISSIONS (
    PERMISSION_ID          INT AUTO_INCREMENT PRIMARY KEY,
    PERMISSION_PROFILEID   INT NOT NULL,
    PERMISSION_ACTIONID    INT NOT NULL,
    PERMISSION_MODULEID    INT NOT NULL,
    PERMISSION_CODE        VARCHAR(30) NOT NULL UNIQUE,
    PERMISSION_DESCRIPTION TEXT NULL,
    PERMISSION_CREATEBY    INT NULL,
    PERMISSION_UPDATEBY    INT NULL,
    PERMISSION_CREATEAT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PERMISSION_UPDATEAT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT FK_PERM_PROFILE FOREIGN KEY (PERMISSION_PROFILEID)
        REFERENCES PROFILES(PROFILE_ID) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_PERM_ACTION  FOREIGN KEY (PERMISSION_ACTIONID)
        REFERENCES ACTIONS(ACTION_ID) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_PERM_MODULE  FOREIGN KEY (PERMISSION_MODULEID)
        REFERENCES MODULES(MODULE_ID) ON DELETE CASCADE ON UPDATE CASCADE,

    CONSTRAINT UQ_PERM_TRIO UNIQUE (PERMISSION_PROFILEID, PERMISSION_ACTIONID, PERMISSION_MODULEID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 5. UTILIZADORES
-- =====================================================================
CREATE TABLE IF NOT EXISTS USERS (
    USER_ID          INT AUTO_INCREMENT PRIMARY KEY,
    USER_EMPLOYEEID  INT NULL UNIQUE,
    USER_PROFILEID   INT NOT NULL,
    USER_USERNAME    VARCHAR(50)  NOT NULL UNIQUE,
    USER_PASSWORDHASH VARCHAR(255) NOT NULL,
    USER_FULLNAME    VARCHAR(150) NULL,
    USER_EMAIL       VARCHAR(100) NULL UNIQUE,
    USER_STATUS      ENUM('ACTIVE','BLOCKED','INACTIVE') DEFAULT 'ACTIVE',
    USER_LASTLOGIN   TIMESTAMP NULL,
    USER_CREATEBY    INT NULL,
    USER_UPDATEBY    INT NULL,
    USER_CREATEAT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    USER_UPDATEAT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT FK_USER_PROFILE FOREIGN KEY (USER_PROFILEID)
        REFERENCES PROFILES(PROFILE_ID) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 6. SESSÕES
-- =====================================================================
CREATE TABLE IF NOT EXISTS USER_SESSIONS (
    SESSION_ID        VARCHAR(255) PRIMARY KEY,
    SESSION_USERID    INT NOT NULL,
    SESSION_IPADDRESS VARCHAR(45)  NULL,
    SESSION_USERAGENT TEXT         NULL,
    SESSION_EXPIRESAT TIMESTAMP NOT NULL,
    SESSION_CREATEAT  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_SESS_USER FOREIGN KEY (SESSION_USERID)
        REFERENCES USERS(USER_ID) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================================
-- 7. LOGS DE AUDITORIA
-- =====================================================================
CREATE TABLE IF NOT EXISTS LOGS (
    LOG_ID         INT AUTO_INCREMENT PRIMARY KEY,
    LOG_USER_ID    INT NULL,
    LOG_ACTION     ENUM('INSERT','UPDATE','DELETE','LOGIN','LOGOUT','ACCESS_DENIED') NOT NULL,
    LOG_TABLE_NAME VARCHAR(100) NOT NULL,
    LOG_RECORD_ID  INT NULL,
    LOG_OLD_DATA   JSON NULL,
    LOG_NEW_DATA   JSON NULL,
    LOG_IPADDRESS  VARCHAR(45) NULL,
    LOG_CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_LOG_USER FOREIGN KEY (LOG_USER_ID)
        REFERENCES USERS(USER_ID) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

